#!/bin/bash
# Push the fix for stale data/photos.js cache — admin Hero/Photos
# publishes were updating the deployed file, but visitors' browsers
# kept seeing the old version because the <script> tag had no
# cache buster. Now the build substitutes a fresh timestamp on
# every deploy.
set -uo pipefail

cd "$(dirname "$0")" || exit 1

echo "=== Working in: $(pwd) ==="
echo ""

echo "=== 1. Removing stale .git/index.lock (if any) ==="
if [ -e .git/index.lock ]; then
  if rm -f .git/index.lock 2>/dev/null; then
    echo "    ok"
  else
    sudo rm -f .git/index.lock || { echo "    sudo failed - STOP"; exit 2; }
    sudo chown -R "$(whoami):staff" .git
  fi
else
  echo "    (no lock - fine)"
fi
echo ""

echo "=== 2. Current state ==="
git status --short
echo ""

echo "=== 3. Staging files ==="
git add index.html scripts/build-photos.js data/photos.js data/photos.json push-now.sh
echo "    staged"
echo ""

echo "=== 4. Committing ==="
git commit -m "Fix stale data/photos.js — cache-bust on every build

Why admin Hero/Photos publishes appeared to do nothing: the
<script src=\"data/photos.js\"> tag on index.html had no ?v=
query string. So every build regenerated data/photos.js
correctly, Netlify uploaded the new file, but visitors' browsers
kept serving the previously cached copy from HTTP cache.

Fix has two parts:
1. index.html now declares the script as
     <script src=\"data/photos.js?v=BUILDTIME\" …>
   with a BUILDTIME placeholder.
2. scripts/build-photos.js does a regex replace after writing
   data/photos.js: it substitutes 'BUILDTIME' (or any previously
   baked-in timestamp) with a fresh YYYYMMDDTHHmmss string. The
   regex covers both the literal placeholder and any old
   timestamp so re-running the build always produces the latest.

Effect: every Netlify build (whether triggered by a push or by
an admin Publish action) puts a brand-new ?v=... on the data
file, forcing every visitor's browser to re-fetch. No more
'I changed something and nothing updated' confusion.

Side effect: data/photos.js + data/photos.json regenerated by the
local test run, so the committed copies match what the build
would produce. They get regenerated on every deploy regardless.

This fix applies retroactively too — the next deploy will bake
a fresh timestamp, so the Hero changes Wendy already published
(steph at slot 4, lauren-w at slot 5) will finally appear for
returning visitors after the next build goes green."
echo ""

echo "=== 5. Pushing ==="
git push
echo ""

echo "=== DONE - watch Netlify deploy log ==="
